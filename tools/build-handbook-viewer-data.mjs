import { createHash } from 'node:crypto';
import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';

const repositoryRoot = path.resolve(import.meta.dirname, '..');
const outputPath = path.join(repositoryRoot, 'handbook-viewer', 'technical-fee-data.js');
const evidenceRoot = path.join(repositoryRoot, 'handbook-viewer', 'assets');
const execFileAsync = promisify(execFile);
const configPath = path.join(process.env.APPDATA || '', 'Codex', 'obsidian-memory.json');
const config = JSON.parse(await readFile(configPath, 'utf8'));
const vaultPath = path.resolve(config.vaultPath);
const files = [
  ['dollar', 'Codex/Index/技術料カタログ.json'],
  ['sharp', 'Codex/Index/技術料シャープマークカタログ.json'],
];
const catalogs = await Promise.all(files.map(async ([mark, relativePath]) => {
  const catalogPath = path.join(vaultPath, ...relativePath.split('/'));
  const catalog = JSON.parse(await readFile(catalogPath, 'utf8'));
  if (catalog.schemaVersion !== 3 || catalog.validation?.status !== 'verified' || catalog.mark !== mark) {
    throw new Error(`${relativePath} は検証済みSchema 3カタログではありません。`);
  }
  const sourcePath = path.join(vaultPath, ...catalog.sourcePdf.split('/'));
  const sourceHash = createHash('sha256').update(await readFile(sourcePath)).digest('hex');
  if (sourceHash !== catalog.sourceSha256) throw new Error(`${relativePath} の原本SHA-256が一致しません。`);
  return { mark, catalog, sourcePath };
}));
const rows = catalogs.flatMap(({ mark, catalog }) => catalog.rows.map((row) => ({
  key: `${mark}:${row.category || 'sharp'}:${row.number}:${row.rankKey}`,
  mark,
  category: row.category || 'sharp',
  number: row.number,
  rank: row.rank,
  minutes: row.minutes,
  xYen: row.xYen,
  tYen: row.tYen,
  standardYen: row.standardYen,
  technicalFee3: row.technicalFee3 || null,
}))).sort((left, right) => left.mark.localeCompare(right.mark) || left.category.localeCompare(right.category) || left.number - right.number);
const metadata = Object.fromEntries(catalogs.map(({ mark, catalog }) => [mark, { sourceSha256: catalog.sourceSha256, sourcePdfPage: catalog.sourcePdfPage, sourcePrintedPage: catalog.sourcePrintedPage, rowCount: catalog.rows.length }]));
await writeFile(outputPath, `/* Generated by tools/build-handbook-viewer-data.mjs. Do not edit manually. */\nwindow.HANDBOOK_TECHNICAL_FEES = ${JSON.stringify({ schemaVersion: 1, generatedAt: new Date().toISOString(), metadata, rows })};\n`, 'utf8');
await renderEvidencePages(catalogs[0].sourcePath);
console.log(`Generated ${rows.length} technical-fee rows: ${path.relative(repositoryRoot, outputPath)}`);

async function renderEvidencePages(sourcePdf) {
  const candidates = [
    process.env.PDFTOPPM_PATH,
    path.join(process.env.USERPROFILE || '', '.cache', 'codex-runtimes', 'codex-primary-runtime', 'dependencies', 'native', 'poppler', 'Library', 'bin', 'pdftoppm.exe'),
    'pdftoppm.exe',
  ].filter(Boolean);
  let executable;
  for (const candidate of candidates) {
    try { await access(candidate); executable = candidate; break; } catch { /* PATH lookup is handled by execFile below. */ }
  }
  executable ||= 'pdftoppm.exe';
  await mkdir(evidenceRoot, { recursive: true });
  for (const page of [7, 8]) {
    await execFileAsync(executable, ['-f', String(page), '-l', String(page), '-png', '-r', '160', '-singlefile', sourcePdf, path.join(evidenceRoot, `fee-page-${page}`)]);
  }
}
